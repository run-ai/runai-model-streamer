"""Generate the third-party notice files from components.json.

    python3 generate.py fetch   download every license/NOTICE file listed in components.json
    python3 generate.py build   write <library>.txt for each native library, and sdk.txt (their union)
    python3 generate.py check   fail if the committed output differs from what build would write

See README.md for how components.json is produced and kept up to date.
"""

import hashlib
import io
import json
import os
import re
import sys
import tarfile
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
LICENSES = os.path.join(HERE, "licenses")
APACHE_MARKER = "END OF TERMS AND CONDITIONS"
RULE = "=" * 78


def load():
    with open(os.path.join(HERE, "components.json")) as f:
        return json.load(f)


def local_path(component, entry):
    if "local" in entry:
        return os.path.join(HERE, entry["local"])
    return os.path.join(LICENSES, component["id"], entry["name"])


def fetch():
    missing = []
    for component in load()["components"]:
        for entry in component["files"]:
            if "local" in entry:
                continue
            path = local_path(component, entry)
            if os.path.exists(path):
                continue
            os.makedirs(os.path.dirname(path), exist_ok=True)
            try:
                with urllib.request.urlopen(entry["url"], timeout=120) as response:
                    data = response.read()
            except urllib.error.HTTPError as error:
                missing.append("%s %s (%s)" % (component["id"], entry["name"], error.code))
                continue
            if "member" in entry:
                with tarfile.open(fileobj=io.BytesIO(data)) as archive:
                    names = [n for n in archive.getnames() if n.endswith("/" + entry["member"]) or n == entry["member"]]
                    data = archive.extractfile(sorted(names, key=len)[0]).read()
            with open(path, "wb") as f:
                f.write(data)
            print("fetched", component["id"], entry["name"])
    if missing:
        sys.exit("not found upstream, remove from components.json if the project has no such file:\n  " + "\n  ".join(missing))


def read(component, entry):
    with open(local_path(component, entry), encoding="utf-8", errors="replace") as f:
        return f.read().rstrip() + "\n"


def apache_body(text):
    """An Apache-2.0 text from its title on, whitespace-normalised. Anything a project appends
    after the standard appendix (extra license texts) makes the result differ from the canonical."""
    text = text[text.find("Apache License"):]
    return re.sub(r"\s+", " ", text).strip()


def is_apache_standard(text, canonical):
    return APACHE_MARKER in text and apache_body(text) == canonical


def build_one(data, libs, title):
    components = [c for c in data["components"] if set(c["libs"]) & set(libs)]
    with open(os.path.join(HERE, "..", "LICENSE"), encoding="utf-8") as f:
        apache_text = f.read()
    apache_text = apache_text[apache_text.find("Apache License"):].rstrip() + "\n"
    canonical = apache_body(apache_text)
    out = [
        "THIRD-PARTY NOTICES",
        title,
        "",
        "This file lists the third-party software that is compiled into the native",
        "libraries named above, with the copyright notice and license text each one",
        "requires. Generated by third_party_notices/generate.py from components.json;",
        "do not edit by hand.",
        "",
        "CONTENTS",
    ]
    for i, c in enumerate(components, 1):
        out.append("  %2d. %s %s - %s" % (i, c["name"], c["version"], c["spdx"]))
    uses_apache = False
    for i, c in enumerate(components, 1):
        out += ["", RULE, "[%d] %s" % (i, c["name"]), RULE, "Version:   " + c["version"],
                "Project:   " + c["url"], "License:   " + c["spdx"], "Copyright: " + c["copyright"],
                "Linkage:   " + c["linkage"]]
        if len(libs) > 1:
            out.append("Used by:   " + ", ".join(l for l in sorted(libs) if l in c["libs"]))
        if c.get("note"):
            out.append("Note:      " + c["note"])
        for entry in c["files"]:
            text = read(c, entry)
            if is_apache_standard(text, canonical):
                out += ["", "License text: Apache License, Version 2.0 - see Appendix A."]
                uses_apache = True
            else:
                out += ["", "--- %s ---" % entry["name"], text.rstrip()]
    if uses_apache:
        out += ["", RULE, "Appendix A - Apache License, Version 2.0", RULE, apache_text.rstrip()]
    return "\n".join(out) + "\n"


def outputs():
    data = load()
    libs = list(data["libraries"])
    files = {}
    for lib in libs:
        files[lib + ".txt"] = build_one(data, [lib], "Library: %s.so (%s)" % (lib, data["libraries"][lib]))
    files["sdk.txt"] = build_one(data, libs, "C/C++ SDK archive: " + ", ".join(l + ".so" for l in libs))
    return files


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "fetch":
        fetch()
    elif command == "build":
        for name, text in outputs().items():
            with open(os.path.join(HERE, name), "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote", name, len(text))
    elif command == "check":
        stale = []
        for name, text in outputs().items():
            path = os.path.join(HERE, name)
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                stale.append(name)
        if stale:
            sys.exit("out of date, run generate.py build: " + ", ".join(stale))
        print("up to date")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
